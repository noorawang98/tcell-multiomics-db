#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""selftest_download.py — 验证「批量下载脚本」这一功能本身。

做三件事（都不需要 sudo）：
  1. 用 downloads.json 里的真实清单生成 Bash 脚本（与网页同一套规则）；
  2. 用 `bash -n` 做语法检查，并静态核对：只出现官方 GEO/SRA 地址、无 sudo、无自动解压、
     含断点续传/重试/日志/失败汇总/依赖检查；
  3. `--download` 时真的执行一次下载（默认取清单里体积最小的 1-2 个数据集），
     校验落地文件的字节数与官方元数据一致，并检查“重复运行不覆盖完整文件”。

用法:
    python3 selftest_download.py                     # 只做 1+2（不联网）
    python3 selftest_download.py --download           # 额外真实下载最小数据集
    python3 selftest_download.py --download --acc GSE151511 --max-mb 200
    python3 selftest_download.py --sra                # 另外生成一份 SRA 脚本并做语法检查
"""
import argparse, json, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
DL = os.path.join(HERE, "site", "data", "downloads.json")

# 与 site/assets/downloads.js 的 scriptFor() 保持同一套规则（Python 版，便于 CI 校验）
HEADER = """#!/usr/bin/env bash
# __TITLE__ batch download script  (generated by selftest_download.py for verification)
# datasets: __ACCS__
set -uo pipefail
BASE_DIR="$(cd "$(dirname "$0")" && pwd)"
RAW_DIR="${RAW_DIR:-$BASE_DIR/raw}"
LOG_DIR="${LOG_DIR:-$BASE_DIR/logs}"
RESUME="${RESUME:-1}"
MAX_RETRY="${MAX_RETRY:-3}"
mkdir -p "$RAW_DIR" "$LOG_DIR"
LOG="$LOG_DIR/download_$(date +%Y%m%d_%H%M%S).log"
FAILED_LIST="$LOG_DIR/failed_$(date +%Y%m%d_%H%M%S).txt"
FAILED=0; OK=0; SKIPPED=0
log(){ printf '%s %s\\n' "$(date '+%F %T')" "$*" | tee -a "$LOG"; }
fail(){ printf '%s\\n' "$1" >> "$FAILED_LIST"; FAILED=$((FAILED+1)); log "[FAIL] $1"; }
HAVE_CURL=0; HAVE_WGET=0
command -v curl >/dev/null 2>&1 && HAVE_CURL=1
command -v wget >/dev/null 2>&1 && HAVE_WGET=1
if [ "$HAVE_CURL" = 0 ] && [ "$HAVE_WGET" = 0 ]; then
  echo "need curl or wget" >&2; exit 2
fi
if [ "$HAVE_CURL" = 1 ]; then
  CURL_VER="$(curl --version 2>/dev/null | head -1)"
  case "$CURL_VER" in *"libcurl/"*) : ;; *) log "curl looks minimal; will fall back" ;; esac
fi
DISK_AVAIL_KB=$(df -Pk "$RAW_DIR" 2>/dev/null | awk 'NR==2{print $4}')
DISK_AVAIL_KB=${DISK_AVAIL_KB:-0}
download_file(){
  local url="$1" dest="$2" want="${3:-}"
  mkdir -p "$(dirname "$dest")"
  if [ -s "$dest" ] && [ -n "$want" ] && [ "$(stat -c%s "$dest" 2>/dev/null || echo 0)" = "$want" ]; then
    log "[SKIP] $dest"; SKIPPED=$((SKIPPED+1)); return 0
  fi
  local n=0 ok=0
  while [ "$n" -lt "$MAX_RETRY" ]; do
    n=$((n+1))
    log "[GET ] $url -> $dest (try $n)"
    if [ "$HAVE_CURL" = 1 ]; then
      curl -fL --retry 3 --retry-delay 2 --connect-timeout 20 -C - -o "$dest" "$url" >>"$LOG" 2>&1 && ok=1
    else
      wget -c --tries=3 --waitretry=2 --timeout=20 -O "$dest" "$url" >>"$LOG" 2>&1 && ok=1
    fi
    [ "$ok" = 1 ] && break
    sleep $((n*3))
  done
  if [ "$ok" != 1 ]; then fail "$url -> $dest"; return 1; fi
  if [ -n "$want" ]; then
    local got; got=$(stat -c%s "$dest" 2>/dev/null || echo 0)
    if [ "$got" != "$want" ]; then fail "$dest size mismatch"; return 1; fi
  fi
  OK=$((OK+1)); log "[OK  ] $dest"
}
"""

FOOTER = """
echo
log "done: ok=$OK skipped=$SKIPPED failed=$FAILED"
if [ "$FAILED" -gt 0 ]; then cat "$FAILED_LIST"; exit 1; fi
"""


def shq(s):
    return "'" + str(s).replace("'", "'\\''") + "'"


def build_script(data, accs, kind):
    hdr = (HEADER.replace("__TITLE__", "GEO supplementary files" if kind == "geo" else "SRA raw data")
                 .replace("__ACCS__", ",".join(accs)))
    out = [hdr]
    for a in accs:
        r = data["datasets"][a]
        d = '"$RAW_DIR"/' + shq(a)
        out.append(f"\n# ---- {a} ----")
        out.append(f"mkdir -p {d}")
        if kind == "geo":
            for f in r["geo"]["files"]:
                want = str(f["b"]) if (f.get("b") and f.get("exact")) else "''"
                out.append(f"download_file {shq(f['u'])} {d}/{shq(f['n'])} {want}")
        else:
            out.append('command -v prefetch >/dev/null 2>&1 || { echo "需要 SRA Toolkit 的 prefetch（不解压安装，无需 sudo）" >&2; exit 2; }')
            out.append('command -v fasterq-dump >/dev/null 2>&1 || '
                       'echo "提示：未找到 fasterq-dump，本脚本只下载 .sra，不做 FASTQ 转换"')
            for run in r["sra"].get("runs", []):
                out.append(f"# {run}: {r['sra'].get('study')} "
                           f"(prefetch {run} --output-directory {d})")
                out.append(f"prefetch --max-size u --output-directory {d} {shq(run)} "
                           f">>\"$LOG\" 2>&1 || fail {shq(run)}")
    out.append(FOOTER)
    return "\n".join(out) + "\n"


def static_checks(text):
    bad = []
    for u in re.findall(r"https?://[^\s'\"]+", text):
        if not (u.startswith("https://ftp.ncbi.nlm.nih.gov/geo/series/")
                or u.startswith("https://sra-download") or "sra" in u):
            bad.append("非官方地址: " + u)
    for pat, msg in [(r"\bsudo\b", "出现 sudo"), (r"\btar\s+-x", "出现自动解压 tar"),
                     (r"\bgunzip\b", "出现自动解压 gunzip"), (r"\brm\s+-rf\b", "出现 rm -rf")]:
        if re.search(pat, text):
            bad.append(msg)
    for need, msg in [('command -v curl', "缺少 curl 存在性检查"),
                      ('curl --version', "缺少 curl 版本/可移植性判断"),
                      ("df -Pk", "缺少磁盘空间检查"),
                      ("-C -", "缺少断点续传 (-C -)"), ("MAX_RETRY", "缺少有限重试"),
                      ("LOG=", "缺少日志"), ("fail(", "缺少失败记录"),
                      ("HAVE_CURL", "缺少依赖检查"), ("stat -c%s", "缺少体积校验")]:
        if need not in text:
            bad.append("缺少: " + msg)
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--download", action="store_true", help="真实下载最小数据集以验证脚本可用")
    ap.add_argument("--acc", default="", help="指定用于真实下载的数据集")
    ap.add_argument("--max-mb", type=int, default=400, help="真实下载的体积上限（MB）")
    ap.add_argument("--sra", action="store_true", help="额外生成 SRA 脚本做语法检查")
    args = ap.parse_args()

    if not os.path.exists(DL):
        sys.exit("缺少 site/data/downloads.json：先运行 python3 fetch_download_manifest.py --sra")
    data = json.load(open(DL, encoding="utf-8"))
    ds = data["datasets"]
    geo_ok = [a for a, r in ds.items() if r["geo"].get("files")]
    unver = [a for a, r in ds.items() if not r["geo"].get("files")]
    print(f"清单：{len(ds)} 个数据集 · 可下载 {len(geo_ok)} · 无法核实 {len(unver)}")
    if unver:
        print("  无法核实（不生成命令）示例：", ", ".join(unver[:5]))

    # 1) 生成脚本（GEO）
    accs = geo_ok[:3] if geo_ok else []
    if not accs:
        sys.exit("清单里没有可下载的数据集")
    text = build_script(data, accs, "geo")
    with tempfile.TemporaryDirectory() as td:
        sp = os.path.join(td, "download_datasets.sh")
        open(sp, "w", encoding="utf-8").write(text)
        # 2) 语法检查
        r = subprocess.run(["bash", "-n", sp], capture_output=True, text=True)
        print("bash -n：", "OK" if r.returncode == 0 else "失败\n" + r.stderr)
        assert r.returncode == 0, r.stderr
        bad = static_checks(text)
        print("静态检查：", "OK" if not bad else bad)
        assert not bad, bad
        if args.sra:
            sra_accs = [a for a, r in ds.items() if r["sra"].get("available")][:2]
            if sra_accs:
                st = build_script(data, sra_accs, "sra")
                sp2 = os.path.join(td, "download_sra.sh")
                open(sp2, "w", encoding="utf-8").write(st)
                r2 = subprocess.run(["bash", "-n", sp2], capture_output=True, text=True)
                print("SRA 脚本 bash -n：", "OK" if r2.returncode == 0 else r2.stderr)
                assert r2.returncode == 0
        # 3) 真实下载（可选）
        if args.download:
            pick = args.acc or min(geo_ok, key=lambda a: ds[a]["geo"]["bytes"] or 1 << 62)
            r0 = ds[pick]
            mb = (r0["geo"]["bytes"] or 0) / 1024 / 1024
            print(f"真实下载验证：{pick}（官方合计 {mb:.1f} MB，上限 {args.max_mb} MB）")
            if mb > args.max_mb:
                print(f"  跳过：超过 --max-mb {args.max_mb}；可用 --acc 指定更小的数据集")
            else:
                work = os.path.join(td, "download")
                os.makedirs(work, exist_ok=True)
                sp3 = os.path.join(work, "download_datasets.sh")
                open(sp3, "w", encoding="utf-8").write(build_script(data, [pick], "geo"))
                r3 = subprocess.run(["bash", sp3], capture_output=True, text=True, cwd=work)
                print("  运行退出码：", r3.returncode)
                print("  " + "\n  ".join(r3.stdout.strip().splitlines()[-4:]))
                got = {}
                for root, _d, names in os.walk(os.path.join(work, "raw")):
                    for n in names:
                        got[n] = os.path.getsize(os.path.join(root, n))
                exp = {f["n"]: f["b"] for f in r0["geo"]["files"] if f.get("b")}
                ok = all(got.get(k) == v for k, v in exp.items()) and got
                print("  落地文件：", got)
                print("  与官方字节数一致：", "是" if ok else f"否（预期 {exp}）")
                assert r3.returncode == 0 and ok, (r3.returncode, got, exp)
                # 重复运行应跳过（不覆盖完整文件）
                r4 = subprocess.run(["bash", sp3], capture_output=True, text=True, cwd=work)
                skipped = "SKIP" in r4.stdout
                print("  重复运行跳过已有完整文件：", "是" if skipped else "否")
                assert skipped
    print("\n自检通过：脚本生成、语法、依赖/续传/重试/日志/汇总、真实下载与字节校验")


if __name__ == "__main__":
    main()
